def build_prompt(tech_stack: str, target_type: BuildTargetType, spec: str) -> str:
    """Build a rich, stack-aware code-generation prompt for the LLM provider."""
    kind = target_type.value.replace("_", " ")
    lead = "You are an expert software engineer. Build a complete, runnable " + kind
    if tech_stack:
        lead += f" using {tech_stack}"
    lead += "."
    if spec:
        lead += f"\n\nRequirements:\n{spec}"
    if tech_stack in _BACKEND_STACKS:
        depth = (
            "Include a data model, full CRUD endpoints (list, create, read, update, delete) "
            "with input validation, a database layer (use SQLite by default), JWT-based "
            "authentication (register, login, and a protected route), and a test file. "
            "Organise the code into multiple files."
        )
    elif tech_stack in _FRONTEND_STACKS:
        depth = (
            "Include a list view, a create/edit form with client-side validation, state "
            "management, and calls to a REST API. Organise into components across multiple "
            "files and include a test."
        )
    elif tech_stack in _MOBILE_STACKS:
        depth = (
            "Include a list screen, a detail/create screen, navigation, state management, "
            "and a test."
        )
    elif tech_stack in _DATA_STACKS:
        depth = (
            "Include data loading, a transformation/analysis step, a clear summary or output, "
            "and a test where applicable."
        )
    else:
        depth = (
            "Produce a complete, correct, runnable artifact with sensible structure and a "
            "test where applicable."
        )
    tail = (
        "\n\nReturn ONLY a JSON object mapping relative file paths to their full file "
        "contents. No prose, no markdown, no code fences. Example: "
        '{"path/to/file": "...file contents..."}.'
    )
    return lead + "\n\n" + depth + tail


def _default_filename(target_type: BuildTargetType, tech_stack: str) -> str:
    if tech_stack in _FRONTEND_STACKS or target_type in (
        BuildTargetType.WEB_APP,
        BuildTargetType.WEBSITE,
    ):
        return "index.html"
    if tech_stack.startswith("python"):
        return "main.py"
    return "GENERATED.md"


def _parse_generated_files(
    raw: str, target_type: BuildTargetType, tech_stack: str
) -> dict[str, str]:  # noqa: E501
    """Parse an LLM response into a {path: content} map, or fall back to one file."""
    try:
        data = json.loads(raw)
    except (json.JSONDecodeError, ValueError):
        data = None
    if (
        isinstance(data, dict)
        and data
        and all(isinstance(k, str) and isinstance(v, str) for k, v in data.items())
    ):
        return dict(data)
    return {_default_filename(target_type, tech_stack): raw}


class LLMProvider:
    """Generates via a configured LLM. Active only when an API key is set."""

    name = "llm"

    def __init__(self, settings: Settings) -> None:
        self._settings = settings
        self.name = settings.codegen_provider

    def generate(
        self, spec: str, target_type: BuildTargetType, tech_stack: str = ""
    ) -> GeneratedArtifact:
        s = self._settings
        headers = {
            "Content-Type": "application/json",
            "x-api-key": s.codegen_api_key,
            "anthropic-version": "2023-06-01",
            "authorization": f"Bearer {s.codegen_api_key}",
        }
        body: dict[str, object] = {
            "model": s.codegen_model,
            "max_tokens": s.codegen_max_tokens,
            "system": _SYSTEM,
            "messages": [{"role": "user", "content": build_prompt(tech_stack, target_type, spec)}],
        }
        raw = _strip_fences(llm_complete(s.codegen_base_url, headers, body))
        files = _parse_generated_files(raw, target_type, tech_stack)
        return GeneratedArtifact(
            provider=self.name,
            summary=f"Generated with {self.name} ({s.codegen_model}) \u2014 {len(files)} file(s).",
            files=files,
        )


def get_codegen_provider(settings: Settings) -> CodeGenProvider:
    """Return the configured provider — LLM when a key is set, else template."""
    if settings.codegen_provider != "template" and settings.codegen_api_key:
        return LLMProvider(settings)
    return TemplateProvider()


