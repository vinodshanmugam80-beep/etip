def scaffold_for_stack(spec: str, tech_stack: str) -> GeneratedArtifact | None:
    """Return a scaffold (plus a starter test) for a known tech stack, or None."""
    builder = _STACK_SCAFFOLDS.get(tech_stack)
    if builder is None:
        return None
    files = builder(spec)
    framework = _STACK_FRAMEWORK.get(tech_stack)
    if framework and framework in _TEST_FILES:
        for path, content in _TEST_FILES[framework].items():
            files.setdefault(path, content)
    return GeneratedArtifact(
        provider="template",
        summary=f"Generated a {tech_stack} scaffold with a starter test ({', '.join(sorted(files))}).",  # noqa: E501
        files=files,
    )


