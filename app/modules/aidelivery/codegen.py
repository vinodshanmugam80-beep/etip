@dataclass
class GeneratedArtifact:
    """The output of a generation run."""

    provider: str
    summary: str
    files: dict[str, str] = field(default_factory=dict)


class CodeGenProvider(Protocol):
    """A provider that generates source files from a spec."""

    name: str

    def generate(
        self, spec: str, target_type: BuildTargetType, tech_stack: str = ""
    ) -> GeneratedArtifact: ...


