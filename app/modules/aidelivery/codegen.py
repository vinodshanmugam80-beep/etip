def llm_complete(url: str, headers: dict[str, str], body: dict[str, object]) -> str:
    """POST a completion request and return the model's text.

    Isolated so tests can mock it; supports Anthropic-style responses (a ``content``
    list of blocks) and OpenAI-style (``choices[0].message.content``).
    """
    req = urllib.request.Request(
        url, data=json.dumps(body).encode(), headers=headers, method="POST"
    )
    with urllib.request.urlopen(req, timeout=60) as resp:  # noqa: S310
        data = json.loads(resp.read().decode())
    if isinstance(data.get("content"), list):  # Anthropic
        return "".join(b.get("text", "") for b in data["content"] if b.get("type") == "text")
    choices = data.get("choices")  # OpenAI-style
    if isinstance(choices, list) and choices:
        return str(choices[0].get("message", {}).get("content", ""))
    return ""


def _strip_fences(text: str) -> str:
    t = (text or "").strip()
    if t.startswith("```"):
        t = t.split("\n", 1)[-1]
        if t.endswith("```"):
            t = t[: t.rfind("```")]
    return t.strip()


