"""Code generation for the AI Delivery "generate" stage.

A pluggable provider turns a build request's spec into generated source files:

* :class:`TemplateProvider` — deterministic, dependency-free, works with no API
  key. Produces a real, runnable starter scaffold for the target type. This is the
  honest baseline: it always works and is fully tested.
* :class:`LLMProvider` — calls a configured LLM (Anthropic / OpenAI-style) to
  generate the app from the spec. Active only when ``codegen_api_key`` is set. The
  HTTP call is isolated in :func:`llm_complete` so it can be mocked in tests and
  swapped per provider; nothing here fabricates model output.

:func:`get_codegen_provider` picks the provider from settings.
"""

